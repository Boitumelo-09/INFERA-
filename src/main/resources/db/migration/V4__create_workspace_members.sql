CREATE TABLE workspace_members (
                                   id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   workspace_id BIGINT       NOT NULL,
                                   user_id      BIGINT       NOT NULL,
                                   role         VARCHAR(20)  NOT NULL,
                                   created_at   TIMESTAMP(6) NOT NULL,
                                   CONSTRAINT fk_workspace_members_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces (id),
                                   CONSTRAINT fk_workspace_members_user      FOREIGN KEY (user_id)      REFERENCES users (id),
                                   CONSTRAINT uq_workspace_members_workspace_user UNIQUE (workspace_id, user_id),
                                   CONSTRAINT ck_workspace_members_role CHECK (role IN ('OWNER', 'EDITOR', 'VIEWER'))
);

-- "which workspaces am I in?" (the unique constraint above leads with workspace_id, so it can't serve this)
CREATE INDEX idx_workspace_members_user_id ON workspace_members (user_id);

-- at most one OWNER row per workspace
CREATE UNIQUE INDEX uq_workspace_members_one_owner ON workspace_members (workspace_id) WHERE role = 'OWNER';

-- backfill: every existing workspace gets its OWNER row (safe to re-run)
INSERT INTO workspace_members (workspace_id, user_id, role, created_at)
SELECT w.id, w.user_id, 'OWNER', w.created_at
FROM workspaces w
    ON CONFLICT DO NOTHING;