CREATE TABLE invitations (
                             id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             workspace_id BIGINT       NOT NULL,
                             email        VARCHAR(150) NOT NULL,
                             role         VARCHAR(20)  NOT NULL,
                             token_hash   VARCHAR(64)  NOT NULL,
                             invited_by   BIGINT       NOT NULL,
                             created_at   TIMESTAMP(6) NOT NULL,
                             expires_at   TIMESTAMP(6) NOT NULL,
                             accepted_at  TIMESTAMP(6),
                             accepted_by  BIGINT,
                             declined_at  TIMESTAMP(6),
                             revoked_at   TIMESTAMP(6),
                             CONSTRAINT fk_invitations_workspace   FOREIGN KEY (workspace_id) REFERENCES workspaces (id),
                             CONSTRAINT fk_invitations_invited_by  FOREIGN KEY (invited_by)   REFERENCES users (id),
                             CONSTRAINT fk_invitations_accepted_by FOREIGN KEY (accepted_by)  REFERENCES users (id) ON DELETE SET NULL,
                             CONSTRAINT uq_invitations_token_hash  UNIQUE (token_hash),
                             CONSTRAINT ck_invitations_role        CHECK (role IN ('EDITOR', 'VIEWER')),
                             CONSTRAINT ck_invitations_email_lower CHECK (email = lower(email))
);

CREATE INDEX idx_invitations_email        ON invitations (email);
CREATE INDEX idx_invitations_workspace_id ON invitations (workspace_id);

-- one OPEN invitation per person per workspace (expired-but-unrevoked rows still count as open,
-- so re-inviting revokes the old row first)
CREATE UNIQUE INDEX uq_invitations_one_open ON invitations (workspace_id, email)
    WHERE accepted_at IS NULL AND revoked_at IS NULL AND declined_at IS NULL;